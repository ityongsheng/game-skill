from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from .errors import ValidationError
from .util import atomic_write_text, write_json


def _scalar(value: str) -> Any:
    value = value.strip()
    if value.startswith("[") and value.endswith("]"):
        body = value[1:-1].strip()
        return [item.strip().strip("'\"") for item in body.split(",") if item.strip()]
    if value.isdigit():
        return int(value)
    if value.lower() in {"true", "false"}:
        return value.lower() == "true"
    return value.strip("'\"")


def module_metadata(path: Path) -> dict[str, Any]:
    text = path.read_text("utf-8")
    if not text.startswith("---\n"):
        raise ValidationError(f"模块缺少 YAML 元数据: {path}")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise ValidationError(f"模块 YAML 元数据未闭合: {path}")
    metadata: dict[str, Any] = {}
    for line in text[4:end].splitlines():
        if not line.strip() or line.lstrip().startswith("#") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        metadata[key.strip()] = _scalar(value)
    for required in ("module_id", "title", "triggers", "priority"):
        if required not in metadata:
            raise ValidationError(f"模块元数据缺少 {required}: {path}")
    if not isinstance(metadata["triggers"], list) or not metadata["triggers"]:
        raise ValidationError(f"模块 triggers 必须为非空列表: {path}")
    metadata["path"] = path.as_posix()
    return metadata


def _yaml_quote(value: Any) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def generate_routes(repo_root: Path) -> dict[str, Any]:
    modules_dir = repo_root / "modules"
    modules = []
    for path in sorted(modules_dir.glob("*.md")):
        item = module_metadata(path)
        item["path"] = path.relative_to(repo_root).as_posix()
        modules.append({
            "id": item["module_id"],
            "title": item["title"],
            "path": item["path"],
            "triggers": item["triggers"],
            "priority": int(item["priority"]),
            "description": item.get("description", item["title"]),
        })
    ids = [item["id"] for item in modules]
    if len(ids) != len(set(ids)):
        raise ValidationError("模块 module_id 重复")
    version_path = repo_root / "VERSION"
    version = version_path.read_text("utf-8").strip() if version_path.exists() else "4.0.0"
    static_path = repo_root / "config/static_routes.json"
    resources = json.loads(static_path.read_text("utf-8")) if static_path.exists() else []
    for resource in resources:
        target = repo_root / resource["path"]
        if not target.is_file():
            raise ValidationError(f"静态路由目标不存在: {resource['path']}")
    catalog = {"name": "game-skill", "version": version, "generated": True, "modules": modules, "resources": resources}
    (repo_root / "index").mkdir(parents=True, exist_ok=True)
    write_json(repo_root / "index/module_catalog.json", catalog)
    keywords = sorted({trigger for item in modules + resources for trigger in item["triggers"]})
    lines = [
        "# AUTO-GENERATED by scripts/game-kb generate-routes. DO NOT EDIT.",
        "name: game-skill",
        f"version: {_yaml_quote(version)}",
        "generated: true",
        "trigger:",
        "  keywords:",
    ]
    lines.extend(f"    - {_yaml_quote(item)}" for item in keywords)
    lines.append("intents:")
    for item in sorted(modules + resources, key=lambda value: (-value["priority"], value["id"])):
        lines.extend([
            f"  - id: {_yaml_quote(item['id'])}",
            f"    label: {_yaml_quote(item.get('title', item['id']))}",
            f"    module: {_yaml_quote(item['path'])}",
            f"    priority: {item['priority']}",
            "    triggers:",
        ])
        lines.extend(f"      - {_yaml_quote(trigger)}" for trigger in item["triggers"])
    atomic_write_text(repo_root / "skill.yaml", "\n".join(lines) + "\n")
    return catalog
